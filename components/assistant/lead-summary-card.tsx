"use client";

/**
 * AI lead-qualification card for the admin quote detail page (internal only).
 * Shows the stored QuoteRequest.aiSummary and lets OWNER/STAFF (re)generate it when an AI key is configured.
 */
import { useEffect, useState } from "react";
import { Sparkles } from "lucide-react";
import { api, ApiError } from "@/components/admin/api";
import { Panel } from "@/components/admin/admin-shell";

type Summary = {
  segment: string;
  size: string;
  urgency: string;
  valueBand: string;
  recurringPotential: boolean;
  summary: string;
  nextAction: string;
  missingInfo: string[];
  model?: string;
  generatedAt?: string;
};

const label = (s: string) => s.replace(/-/g, " ");
const VALUE_STYLE: Record<string, string> = { strategic: "bg-navy text-white", high: "bg-orange text-white", medium: "bg-orange-50 text-orange-700", low: "bg-cloud text-slate-ink" };

export function LeadSummaryCard({ quoteId }: { quoteId: string }) {
  const [summary, setSummary] = useState<Summary | null>(null);
  const [available, setAvailable] = useState(false);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api<{ summary: Summary | null; available: boolean }>(`/assistant/quotes/${quoteId}/summary`)
      .then((r) => {
        setSummary(r.summary);
        setAvailable(r.available);
      })
      .catch((e: ApiError) => e.status !== 403 && setError(e.message))
      .finally(() => setLoading(false));
  }, [quoteId]);

  const generate = async () => {
    setBusy(true);
    setError(null);
    try {
      const r = await api<{ summary: Summary }>(`/assistant/quotes/${quoteId}/summary`, { method: "POST" });
      setSummary(r.summary);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  };

  if (loading) return null;
  if (!summary && !available) return null; // no AI key: keep the page clean

  return (
    <Panel
      title="AI lead summary"
      action={available ? <button type="button" onClick={generate} disabled={busy} className="btn-ghost !px-3 !py-1.5 text-xs">{busy ? "Working…" : summary ? "Refresh" : "Generate"}</button> : undefined}
    >
      {error && <p className="mb-2 text-sm text-rose-700" role="alert">{error}</p>}
      {summary ? (
        <div className="space-y-3 text-sm">
          <div className="flex flex-wrap gap-1.5">
            <span className={`rounded-full px-2.5 py-0.5 text-xs font-semibold ${VALUE_STYLE[summary.valueBand] ?? "bg-cloud"}`}>{label(summary.valueBand)} value</span>
            <span className="rounded-full bg-navy-50 px-2.5 py-0.5 text-xs font-semibold text-navy">{label(summary.segment)}</span>
            <span className="rounded-full bg-navy-50 px-2.5 py-0.5 text-xs font-semibold text-navy">{label(summary.size)}</span>
            <span className="rounded-full bg-navy-50 px-2.5 py-0.5 text-xs font-semibold text-navy">urgency: {label(summary.urgency)}</span>
            {summary.recurringPotential && <span className="rounded-full bg-emerald-50 px-2.5 py-0.5 text-xs font-semibold text-emerald-800">recurring potential</span>}
          </div>
          <p className="text-slate-ink">{summary.summary}</p>
          <p className="rounded-xl bg-orange-50 px-3 py-2 text-orange-900"><span className="font-semibold">Next action: </span>{summary.nextAction}</p>
          {summary.missingInfo.length > 0 && (
            <div>
              <p className="text-xs font-semibold uppercase tracking-wider text-muted">Still needed</p>
              <ul className="mt-1 list-disc pl-5 text-slate-ink">{summary.missingInfo.map((m) => <li key={m}>{m}</li>)}</ul>
            </div>
          )}
          <p className="flex items-center gap-1 text-xs text-muted"><Sparkles className="h-3 w-3" aria-hidden /> Generated by AI{summary.model ? ` (${summary.model})` : ""}. Check before acting.</p>
        </div>
      ) : (
        <p className="text-sm text-slate-ink">No summary yet. Generate one to see segment, value and the recommended next step.</p>
      )}
    </Panel>
  );
}
