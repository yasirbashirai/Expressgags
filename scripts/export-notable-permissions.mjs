#!/usr/bin/env node
/**
 * Exports the notable-project IDs with RECORDED written naming permission (DB table
 * NotableProjectPermission, managed in Admin → Website content → History & names) into
 * scripts/notable-permissions.mjs, which scripts/check-content.mjs reads offline.
 *
 * Run before `npm run check:content` on a build that rendered CMS data:
 *   node scripts/export-notable-permissions.mjs            (uses DATABASE_URL / .env)
 * If the database is unreachable the existing file is left unchanged (guardrail stays strict).
 */
import { readFileSync, writeFileSync } from "node:fs";
import pg from "pg";

let url = process.env.DATABASE_URL;
if (!url) {
  try {
    url = readFileSync(".env", "utf8").match(/^DATABASE_URL="?([^"\n]+)"?/m)?.[1];
  } catch {
    /* no .env */
  }
}
if (!url) {
  console.warn("export-notable-permissions: no DATABASE_URL; keeping the current list.");
  process.exit(0);
}

const client = new pg.Client({ connectionString: url, connectionTimeoutMillis: 4000 });
try {
  await client.connect();
  const { rows } = await client.query('SELECT "projectId" FROM "NotableProjectPermission" WHERE "permissionGranted" = true ORDER BY "projectId"');
  const ids = rows.map((r) => r.projectId);
  const file = `/**
 * IDs of notable projects / history entries with RECORDED written permission to name publicly.
 * GENERATED by scripts/export-notable-permissions.mjs from the database (Admin → Website content →
 * History & names). Do not edit by hand. Exported ${new Date().toISOString()}.
 */
export const notableProjectsPublic = ${JSON.stringify(ids, null, 2)};
`;
  writeFileSync("scripts/notable-permissions.mjs", file);
  console.log(`export-notable-permissions: ${ids.length} project(s) with naming permission.`);
} catch (e) {
  console.warn("export-notable-permissions: database unreachable, keeping the current list:", e.message);
} finally {
  await client.end().catch(() => undefined);
}
